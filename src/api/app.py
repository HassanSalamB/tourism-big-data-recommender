def _query_dataframe(conn, query: str, params: tuple[Any, ...] = ()) -> pd.DataFrame:
    with conn.cursor() as cursor:
        cursor.execute(query, params)
        rows = cursor.fetchall()
        columns = [desc[0] for desc in cursor.description]
    return pd.DataFrame(rows, columns=columns)


def _json_records(df: pd.DataFrame) -> list[dict[str, Any]]:
    if df.empty:
        return []
    # Pandas represents missing values as NaN/NaT, but strict JSON does not allow
    # NaN floats. Convert every dataframe missing value to Python None.
    clean_df = df.astype(object).where(pd.notna(df), None)
    return clean_df.to_dict(orient="records")


def _json_value(value):
    return None if pd.isna(value) else value


def _database_ready(conn) -> bool:
    with conn.cursor() as cursor:
        cursor.execute("SELECT to_regclass('public.silver_places')")
        return cursor.fetchone()[0] is not None


def _places_query(where_clause: str = "", limit_clause: str = ""):
    return f"""
        WITH filtered_places AS (
            SELECT
                p.id,
                p.name,
                p.city,
                p.lat,
                p.lon,
                p.address,
                p.description,
                p.website
            FROM silver_places p
            {where_clause}
            ORDER BY p.name
            {limit_clause}
        )
        SELECT
            p.id,
            p.name,
            p.city,
            p.lat,
            p.lon,
            p.address,
            p.description,
            p.website,
            COALESCE(
                ARRAY_AGG(DISTINCT c.name) FILTER (WHERE c.name IS NOT NULL),
                ARRAY[]::TEXT[]
            ) AS categories
        FROM filtered_places p
        LEFT JOIN silver_place_categories pc ON p.id = pc.place_id
        LEFT JOIN silver_categories c ON pc.category_id = c.id
        GROUP BY p.id, p.name, p.city, p.lat, p.lon, p.address, p.description, p.website
        ORDER BY p.name
    """


def _load_places_for_city(conn, city: str, limit: int) -> pd.DataFrame:
    query = _places_query(
        where_clause="WHERE LOWER(p.city) = LOWER(%s)",
        limit_clause="LIMIT %s",
    )
    return _query_dataframe(conn, query, (city, limit))


def _load_city_centroid(conn, city: str) -> tuple[float, float] | None:
    with conn.cursor() as cursor:
        cursor.execute(
            """
            SELECT AVG(lat)::float AS lat, AVG(lon)::float AS lon
            FROM silver_places
            WHERE LOWER(city) = LOWER(%s)
              AND lat IS NOT NULL
              AND lon IS NOT NULL
            """,
            (city,),
        )
        row = cursor.fetchone()
    if not row or row[0] is None or row[1] is None:
        return None
    return float(row[0]), float(row[1])


def _fetch_current_weather(lat: float, lon: float) -> dict[str, Any]:
    response = requests.get(
        "https://api.open-meteo.com/v1/forecast",
        params={
            "latitude": lat,
            "longitude": lon,
            "current": ",".join(
                [
                    "temperature_2m",
                    "relative_humidity_2m",
                    "precipitation",
                    "rain",
                    "weather_code",
                    "wind_speed_10m",
                    "wind_direction_10m",
                ]
            ),
            "timezone": "auto",
        },
        timeout=10,
    )
    response.raise_for_status()
    payload = response.json()
    return payload.get("current") or {}


def _get_recommendations_for_places(
    place_ids: list[str], city: str | None, limit: int = 3
) -> dict[str, list[str]]:
    if not place_ids:
        return {}
    try:
        from neo4j import GraphDatabase, Query

        uri, auth = neo4j_env()
        driver = GraphDatabase.driver(uri, auth=auth, connection_timeout=2)
        try:
            with driver.session() as session:
                result = session.run(
                    Query(
                        """
                    UNWIND $place_ids AS place_id
                    MATCH (p:POI {id: place_id})-[:HAS_CATEGORY]->(:Category)<-[:HAS_CATEGORY]-(similar:POI)
                    OPTIONAL MATCH (similar)-[:LOCATED_IN]->(city:City)
                    WHERE similar.id <> place_id
                      AND ($city IS NULL OR toLower(city.name) = toLower($city))
                      AND similar.label IS NOT NULL
                    WITH place_id, similar.label AS name
                    ORDER BY name
                    WITH place_id, collect(DISTINCT name)[0..$limit] AS recommendations
                    RETURN place_id, recommendations
                    """,
                        timeout=3,
                    ),
                    place_ids=place_ids,
                    city=city,
                    limit=limit,
                )
                return {
                    record["place_id"]: list(record["recommendations"] or [])
                    for record in result
                }
        finally:
            driver.close()
    except Exception:
        return {}


def _row_categories(row) -> list[str]:
    categories = row.get("categories") or []
    return list(categories) if isinstance(categories, (list, tuple)) else []


def _normalize_categories(categories: list[str] | None) -> list[str]:
    if not categories:
        return []
    normalized = []
    seen = set()
    for category in categories:
        cleaned = category.strip()
        key = cleaned.lower()
        if not cleaned or key in seen:
            continue
        normalized.append(cleaned)
        seen.add(key)
    return normalized


def _category_match_count(
    row_categories: list[str], preferred_categories: list[str]
) -> int:
    preferred = {category.lower() for category in preferred_categories}
    return sum(1 for category in row_categories if category.lower() in preferred)


def _haversine_km(lat_a: float, lon_a: float, lat_b: float, lon_b: float) -> float:
    earth_radius_km = 6371.0
    delta_lat = radians(lat_b - lat_a)
    delta_lon = radians(lon_b - lon_a)
    start_lat = radians(lat_a)
    end_lat = radians(lat_b)
    value = (
        sin(delta_lat / 2) ** 2
        + cos(start_lat) * cos(end_lat) * sin(delta_lon / 2) ** 2
    )
    return 2 * earth_radius_km * asin(sqrt(value))


def _average_stop_distance_km(itinerary: list[DayPlan]) -> float:
    distances = []
    for day in itinerary:
        for previous, current in zip(day.places, day.places[1:]):
            distances.append(
                _haversine_km(previous.lat, previous.lon, current.lat, current.lon)
            )
    if not distances:
        return 0.0
    return sum(distances) / len(distances)


def _category_match_rate(
    itinerary: list[DayPlan], preferred_categories: list[str]
) -> float:
    selected_places = [place for day in itinerary for place in day.places]
    if not selected_places:
        return 0.0
    if not preferred_categories:
        return 1.0
    preferred = {category.lower() for category in preferred_categories}
    matched = sum(
        1
        for place in selected_places
        if any(category.lower() in preferred for category in place.categories)
    )
    return matched / len(selected_places)


def _average_recommendation_count(itinerary: list[DayPlan]) -> float:
    selected_places = [place for day in itinerary for place in day.places]
    if not selected_places:
        return 0.0
    return sum(len(place.recommendations) for place in selected_places) / len(
        selected_places
    )


def _is_outdoor_place(place: PlannedPlace) -> bool:
    outdoor_terms = {
        "beach",
        "garden",
        "hiking",
        "lake",
        "natural",
        "nature",
        "outdoor",
        "park",
        "trail",
        "viewpoint",
        "walk",
    }
    category_text = " ".join(place.categories + [place.category]).lower()
    return any(term in category_text for term in outdoor_terms)


def _weather_suitability_score(
    itinerary: list[DayPlan], weather: dict[str, Any] | None
) -> float:
    selected_places = [place for day in itinerary for place in day.places]
    if not selected_places or not weather:
        return 1.0

    outdoor_ratio = sum(1 for place in selected_places if _is_outdoor_place(place)) / len(
        selected_places
    )
    precipitation = float(weather.get("precipitation") or 0)
    rain = float(weather.get("rain") or 0)
    wind_speed = float(weather.get("wind_speed_10m") or 0)
    weather_code = int(weather.get("weather_code") or 0)
    bad_weather = precipitation > 0 or rain > 0 or weather_code >= 51 or wind_speed >= 40
    if not bad_weather:
        return 1.0
    return max(0.0, 1.0 - outdoor_ratio)


def _load_weather_for_itinerary(city: str) -> dict[str, Any] | None:
    try:
        with closing(conn_env()) as conn:
            centroid = _load_city_centroid(conn, city)
        if centroid is None:
            return None
        return _fetch_current_weather(*centroid)
    except Exception:
        return None


def _select_day_rows(
    day_rows: pd.DataFrame, preferred_categories: list[str], max_places: int
) -> list[dict[str, Any]]:
    sorted_rows = day_rows.sort_values(["distance_to_day_center", "name"])
    if not preferred_categories:
        return sorted_rows.head(max_places).to_dict(orient="records")

    return sorted_rows[sorted_rows["category_match_count"] > 0].head(
        max_places
    ).to_dict(orient="records")


def _record_itinerary_quality_metrics(
    city: str,
    itinerary: list[DayPlan],
    preferred_categories: list[str],
    weather: dict[str, Any] | None,
) -> dict[str, float]:
    metrics = {
        "category_match_rate": _category_match_rate(itinerary, preferred_categories),
        "avg_distance_km": _average_stop_distance_km(itinerary),
        "avg_recommendations": _average_recommendation_count(itinerary),
        "weather_suitability_score": _weather_suitability_score(itinerary, weather),
    }
    ITINERARY_CATEGORY_MATCH_RATE.labels(city).set(metrics["category_match_rate"])
    ITINERARY_AVG_DISTANCE_KM.labels(city).set(metrics["avg_distance_km"])
    ITINERARY_AVG_RECOMMENDATIONS.labels(city).set(metrics["avg_recommendations"])
    ITINERARY_WEATHER_SUITABILITY_SCORE.labels(city).set(
        metrics["weather_suitability_score"]
    )
    return metrics


