@app.get("/places")
def places(
    city: str | None = None,
    category: str | None = None,
    categories: list[str] | None = Query(default=None),
    limit: int = Query(default=100, ge=1, le=500),
):
    filters = []
    params: list[Any] = []
    if city:
        filters.append("LOWER(p.city) = LOWER(%s)")
        params.append(city)
    selected_categories = _normalize_categories([category] if category else categories)
    if selected_categories:
        filters.append("""
            EXISTS (
                SELECT 1
                FROM silver_place_categories pc_filter
                JOIN silver_categories c_filter ON pc_filter.category_id = c_filter.id
                WHERE pc_filter.place_id = p.id
                  AND LOWER(c_filter.name) = ANY(%s)
            )
            """)
        params.append([category.lower() for category in selected_categories])

    where_clause = f"WHERE {' AND '.join(filters)}" if filters else ""
    params.append(limit)
    with closing(conn_env()) as conn:
        if not _database_ready(conn):
            raise HTTPException(
                status_code=503, detail="silver_places is not loaded yet."
            )
        df = _query_dataframe(
            conn,
            _places_query(
                where_clause=where_clause,
                limit_clause="LIMIT %s",
            ),
            tuple(params),
        )
    return _json_records(df)


@app.get("/weather/current", response_model=CurrentWeather)
def current_weather(city: str = Query(..., min_length=1)):
    requested_city = city.strip()
    with closing(conn_env()) as conn:
        if not _database_ready(conn):
            raise HTTPException(
                status_code=503, detail="silver_places is not loaded yet."
            )
        centroid = _load_city_centroid(conn, requested_city)

    if centroid is None:
        raise HTTPException(
            status_code=404, detail=f"City '{requested_city}' was not found."
        )

    lat, lon = centroid
    try:
        current = _fetch_current_weather(lat, lon)
    except requests.RequestException as exc:
        WEATHER_REQUESTS_TOTAL.labels(requested_city, "failed").inc()
        raise HTTPException(
            status_code=502, detail=f"Weather provider request failed: {exc}"
        ) from exc

    WEATHER_REQUESTS_TOTAL.labels(requested_city, "ok").inc()
    _publish_platform_event(
        "weather_snapshots",
        "weather.current_requested",
        {
            "city": requested_city,
            "lat": round(lat, 6),
            "lon": round(lon, 6),
            "weather": current,
        },
        key=requested_city.lower(),
    )
    return CurrentWeather(
        city=requested_city,
        lat=round(lat, 6),
        lon=round(lon, 6),
        observed_at=current.get("time"),
        temperature_2m=current.get("temperature_2m"),
        relative_humidity_2m=current.get("relative_humidity_2m"),
        precipitation=current.get("precipitation"),
        rain=current.get("rain"),
        weather_code=current.get("weather_code"),
        wind_speed_10m=current.get("wind_speed_10m"),
        wind_direction_10m=current.get("wind_direction_10m"),
        source="Open-Meteo Forecast API",
    )


@app.post("/generate-itinerary", response_model=list[DayPlan])
def generate_itinerary(request: ItineraryRequest):
    preferred_categories = _normalize_categories(request.categories)
    with closing(conn_env()) as conn:
        if not _database_ready(conn):
            raise HTTPException(
                status_code=503, detail="silver_places is not loaded yet."
            )
        df = _load_places_for_city(
            conn,
            request.city.strip(),
            min(max(request.days * request.max_places_per_day * 50, 500), 2000),
        )

    if df.empty:
        raise HTTPException(
            status_code=404, detail=f"City '{request.city}' was not found."
        )

    cluster_count = min(request.days, len(df))
    if cluster_count > 1:
        coords = df[["lat", "lon"]].astype(float).values
        kmeans = KMeans(
            n_clusters=cluster_count,
            random_state=42,
            n_init=10,
        )
        df["day_assignment"] = kmeans.fit_predict(coords)
        df["distance_to_day_center"] = [
            ((lat - kmeans.cluster_centers_[label][0]) ** 2)
            + ((lon - kmeans.cluster_centers_[label][1]) ** 2)
            for (lat, lon), label in zip(coords, df["day_assignment"])
        ]
    else:
        df["day_assignment"] = 0
        df["distance_to_day_center"] = 0
    df["category_match_count"] = df["categories"].map(
        lambda categories: _category_match_count(
            list(categories or []), preferred_categories
        )
    )
    if preferred_categories:
        df = df[df["category_match_count"] > 0].copy()
        if df.empty:
            raise HTTPException(
                status_code=404,
                detail=(
                    "No places in this city match the selected interests: "
                    f"{', '.join(preferred_categories)}."
                ),
            )

    selected_rows_by_day = []
    for day_index in range(cluster_count):
        selected_rows_by_day.append(
            (
                day_index,
                _select_day_rows(
                    df[df["day_assignment"] == day_index],
                    preferred_categories,
                    request.max_places_per_day,
                ),
            )
        )

    selected_place_ids = [
        row["id"] for _, rows in selected_rows_by_day for row in rows if row.get("id")
    ]
    recommendation_map = _get_recommendations_for_places(
        selected_place_ids, request.city.strip()
    )

    itinerary: list[DayPlan] = []
    for day_index, rows in selected_rows_by_day:
        current_time = datetime.strptime("09:00", "%H:%M")
        planned_places = []

        for row in rows:
            end_time = current_time + timedelta(hours=2)
            categories = _row_categories(row)
            planned_places.append(
                PlannedPlace(
                    id=row["id"],
                    name=row["name"],
                    city=row.get("city"),
                    category=categories[0] if categories else "Tourism",
                    categories=categories,
                    lat=row["lat"],
                    lon=row["lon"],
                    address=_json_value(row.get("address")),
                    description=_json_value(row.get("description")),
                    website=_json_value(row.get("website")),
                    start_time=current_time.strftime("%H:%M"),
                    end_time=end_time.strftime("%H:%M"),
                    recommendations=recommendation_map.get(row["id"], []),
                )
            )
            current_time = end_time + timedelta(minutes=30)

        itinerary.append(DayPlan(day=day_index + 1, places=planned_places))

    selected_count = sum(len(day.places) for day in itinerary)
    requested_city = request.city.strip()
    weather_for_metrics = _load_weather_for_itinerary(requested_city)
    quality_metrics = _record_itinerary_quality_metrics(
        requested_city,
        itinerary,
        preferred_categories,
        weather_for_metrics,
    )
    ITINERARIES_GENERATED_TOTAL.labels(requested_city).inc()
    ITINERARY_PLACES_SELECTED_TOTAL.labels(requested_city).inc(selected_count)
    _publish_platform_event(
        "itinerary_requests",
        "itinerary.generated",
        {
            "city": requested_city,
            "days": request.days,
            "max_places_per_day": request.max_places_per_day,
            "categories": preferred_categories,
            "selected_place_count": selected_count,
            "quality_metrics": quality_metrics,
        },
        key=requested_city.lower(),
    )
    return itinerary


